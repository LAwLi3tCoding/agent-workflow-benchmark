import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pluginRoot = path.join(repoRoot, "plugins", "agent-workflow-benchmark");
const runtimeRoot = path.join(pluginRoot, "runtime");

const copyEntries = ["dist", "configs", "schemas", "fixtures", "package.json", "package-lock.json"];

await rm(runtimeRoot, { recursive: true, force: true });
await mkdir(runtimeRoot, { recursive: true });

for (const entry of copyEntries) {
  await cp(path.join(repoRoot, entry), path.join(runtimeRoot, entry), { recursive: true });
}

await writeFile(
  path.join(runtimeRoot, "README.md"),
  [
    "# Agent Workflow Benchmark Runtime",
    "",
    "This directory is generated by `npm run plugin:build`.",
    "It makes the Codex/Claude Code plugin runnable after marketplace installation without requiring users to clone the source repository.",
    "",
    "Do not edit generated runtime files directly; change the source project and rebuild the plugin runtime."
  ].join("\n")
);
